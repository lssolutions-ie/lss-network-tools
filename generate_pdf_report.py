def _about_table_header(pdf, col):
    """Draw the about-page table column headers at the current Y position."""
    pdf.set_fill_color(*C_NAV)
    pdf.set_text_color(*C_WHT)
    pdf.set_font("Inter", "B", 7.5)
    pdf.set_x(20)
    pdf.cell(col[0], 6, "  #",  fill=True)
    pdf.cell(col[1], 6, "Task", fill=True)
    pdf.cell(col[2], 6, "What it checks and why it matters", fill=True,
             new_x="LMARGIN", new_y="NEXT")


def _measure_row_h(pdf, desc, col_w, line_h):
    """Return the row height needed to fit desc in col_w mm at the current font."""
    words = safe(desc).split()
    lines, line_w = 1, 0.0
    for word in words:
        w = pdf.get_string_width(word + " ")
        if line_w + w > col_w - 1:
            lines += 1
            line_w = w
        else:
            line_w += w
    return max(10.0, lines * line_h + 5)


def render_about_report(pdf, ran_task_ids=None):
    C_ACC      = (74, 144, 226)
    COL        = (12, 52, 106)
    LINE_H     = 3.8
    PAGE_SAFE  = 272   # stop drawing rows below this Y (297mm - ~25mm safety)

    pdf.add_page()
    pdf.set_auto_page_break(False)   # handle page breaks manually for the table

    pdf.section_title("About This Report")

    pdf.set_font("Inter", "", 8)
    pdf.set_text_color(*C_DGR)
    pdf.set_x(20)
    pdf.multi_cell(
        170, 4.5,
        safe("This report was produced by LSS Network Tools (LS Solutions Software). "
             "Each section below corresponds to a specific test run on the client's network. "
             "The table explains what each task checks and why it matters."),
        align="L", new_x="LMARGIN", new_y="NEXT",
    )
    pdf.ln(2)
    _about_table_header(pdf, COL)

    # Only describe tasks that were actually run in this report
    visible = [t for t in TASK_DESCRIPTIONS
               if ran_task_ids is None or t[0] in ran_task_ids]

    for i, (num, name, desc) in enumerate(visible):
        pdf.set_font("Inter", "", 7)
        row_h = _measure_row_h(pdf, desc, COL[2], LINE_H)

        # If this row won't fit, start a new page and redraw the header
        if pdf.get_y() + row_h > PAGE_SAFE:
            pdf.add_page()
            pdf.set_auto_page_break(False)
            _about_table_header(pdf, COL)

        row_y = pdf.get_y()

        # Row background
        pdf.set_fill_color(*C_LGR if i % 2 == 0 else (250, 251, 254))
        pdf.rect(20, row_y, sum(COL), row_h, "F")

        # Left accent stripe
        if   num <= 3: stripe = C_INF
        elif num <= 6: stripe = C_ADV
        elif num <= 9: stripe = C_WRN
        else:          stripe = (130, 80, 180)
        pdf.set_fill_color(*stripe)
        pdf.rect(20, row_y, 2, row_h, "F")

        mid_y = row_y + (row_h - 5) / 2

        # Task number
        pdf.set_font("Inter", "B", 8)
        pdf.set_text_color(*C_NAV)
        pdf.set_xy(22, mid_y)
        pdf.cell(COL[0] - 2, 5, safe(str(num)), align="C")

        # Task name
        pdf.set_xy(20 + COL[0], mid_y)
        pdf.cell(COL[1], 5, safe(name), align="L")

        # Description — vertically centred within the row
        desc_lines  = max(1, round((row_h - 5) / LINE_H))
        desc_top_y  = row_y + (row_h - desc_lines * LINE_H) / 2
        pdf.set_font("Inter", "", 7)
        pdf.set_text_color(*C_DGR)
        pdf.set_xy(20 + COL[0] + COL[1], desc_top_y)
        pdf.multi_cell(COL[2], LINE_H, safe(desc), align="L", new_x="LMARGIN", new_y="NEXT")

        pdf.set_y(row_y + row_h)   # always advance to exact row bottom

    # Footer note
    pdf.ln(3)
    if pdf.get_y() + 12 > PAGE_SAFE:
        pdf.add_page()
        pdf.set_auto_page_break(False)
    pdf.set_draw_color(*C_ACC)
    pdf.set_line_width(0.4)
    pdf.line(20, pdf.get_y(), 190, pdf.get_y())
    pdf.ln(3)
    pdf.set_font("Inter", "I", 8)
    pdf.set_text_color(*C_MGR)
    pdf.set_x(20)
    custom_ran = ran_task_ids is not None and bool(ran_task_ids & {13, 14, 15, 16})
    if custom_ran:
        footer_note = (
            "Custom tasks (13\u201316) were also run as part of this engagement and appear "
            "in the audit results section: custom port scans, stress tests, identity "
            "resolution, and DNS resolver assessment."
        )
    else:
        footer_note = CUSTOM_TASK_NOTE
    pdf.multi_cell(170, 4.5, safe(footer_note), align="L", new_x="LMARGIN", new_y="NEXT")

    pdf.set_auto_page_break(True, margin=20)


# ── Main ──────────────────────────────────────────────────────────────────
def main():
    if len(sys.argv) < 3:
        print("Usage: generate_pdf_report.py <run_output_dir> <app_root>", file=sys.stderr)
        sys.exit(1)

    run_dir  = Path(sys.argv[1])
    app_root = Path(sys.argv[2])
    pdf_path_override = Path(sys.argv[3]) if len(sys.argv) > 3 and sys.argv[3] else None
    prepared_by_arg   = sys.argv[4] if len(sys.argv) > 4 else ""
    logo     = app_root / "assets" / "logo.png"

    manifest        = load_json(run_dir / "manifest.json")        or {}
    findings_data   = load_json(run_dir / "findings.json")        or {}
    remediation_data= load_json(run_dir / "remediation.json")     or {}

    client      = manifest.get("client",       "Unknown Client")
    location    = manifest.get("location",     "Unknown Location")
    note        = manifest.get("note",         "")
    date_stamp  = manifest.get("generated_at", "Unknown Date")
    prepared_by = prepared_by_arg or manifest.get("prepared_by",  "")

    pdf = Report(
        client      = client,
        location    = location,
        note        = note,
        date_stamp  = date_stamp,
        prepared_by = prepared_by,
        logo_path   = str(logo) if logo.exists() else None,
    )
    pdf.add_page()
    pdf.cover()

    # ── About This Report ─────────────────────────────────────────────────
    ran_task_ids = set()
    for t in manifest.get("tasks", []) or []:
        if not isinstance(t, dict):
            continue
        tid = to_int(t.get("task_id"))
        if tid is None:
            continue
        if is_truthy(t.get("json_present")) or all_task_json_paths(run_dir, manifest, tid):
            ran_task_ids.add(tid)
    # Pass None when the set is empty so render_about_report shows all tasks
    # as a safe fallback rather than an empty table.
    render_about_report(pdf, ran_task_ids or None)

    # ── Executive Summary ──────────────────────────────────────────────────
    pdf.add_page()
    pdf.section_title("Executive Summary - Key Findings")
    _SEV_ORDER = {"high": 0, "warning": 1, "info": 2, "advice": 3}
    findings = sorted(
        [f for f in (findings_data.get("findings") or []) if isinstance(f, dict)],
        key=lambda f: _SEV_ORDER.get(str(f.get("severity") or "info").lower(), 99),
    )
    if not findings:
        pdf.note("No notable findings were generated from this scan set.")
    else:
        for i, f in enumerate(findings):
            pdf.finding_row(
                f.get("severity") or "info",
                f.get("title")    or "",
                f.get("detail")   or "",
                shade=i % 2 == 0,
            )

    # ── Remediation Hints ──────────────────────────────────────────────────
    hints = [h for h in (remediation_data.get("hints") or []) if isinstance(h, dict)]
    if hints:
        pdf.section_title("Remediation Hints")
        for i, h in enumerate(hints):
            pdf.hint_row(h.get("title") or "", h.get("detail") or "", shade=i % 2 == 0)

    # ── Audit Results ──────────────────────────────────────────────────────
    pdf.add_page()
    pdf.section_title("Audit Results - Per Task")

    def get(task_id):
        p = task_json_path(run_dir, manifest, task_id)
        return (load_json(p), p) if p and p.exists() else (None, None)

    def note_edited(task_id, d, p):
        marker = edited_marker(d, _manifest_task(manifest, task_id), p)
        if marker:
            pdf.set_font("Inter", "B", 7.5)
            pdf.set_text_color(*C_WRN)
            pdf.multi_cell(0, 4.5, safe(f"  ! This result was {marker}; the values above are not the engine's measurement."),
                           align="L", new_x="LMARGIN", new_y="NEXT")
            pdf.set_text_color(*C_DGR)

    def single(task_id, renderer, *args):
        d, p = get(task_id)
        if d is None:
            return
        renderer(pdf, *args, d) if args else renderer(pdf, d)
        note_edited(task_id, d, p)
        render_task_status(pdf, d)

    def multi(task_id, renderer):
        paths = all_task_json_paths(run_dir, manifest, task_id)
        total = len(paths)
        for pos, p in enumerate(paths, 1):
            d = load_json(p)
            if d is None:
                continue
            idx = device_index(p, pos)
            if task_id == 10:
                renderer(pdf, d, idx, total)
            else:
                renderer(pdf, d, idx)
            note_edited(task_id, d, p)
            render_task_status(pdf, d)

    single(1,  render_interface_info)
    single(2,  render_speed_test)
    single(3,  render_gateway)
    single(4,  render_dhcp)
    single(5,  render_dhcp_response_time)
    single(6,  render_dns_scan)
    single(7,  render_generic_scan, 7, "LDAP/AD Network Scan")
    single(8,  render_smb_nfs)
    single(9,  render_generic_scan, 9, "Printer/Print Server Network Scan")
    multi(10,  render_gateway_stress)
    single(11, render_vlan_trunk)
    single(12, render_duplicate_ip)

    multi(13,  render_custom_port_scan)
    multi(14,  render_custom_stress)
    multi(15,  render_custom_identity)
    multi(16,  render_custom_dns_assessment)

    single(17, render_wireless_survey)
    single(18, render_unifi_discovery)
    single(19, render_unifi_adoption)
    single(20, render_find_device_by_mac)

    # ── Output path ────────────────────────────────────────────────────────
    if pdf_path_override:
        pdf_path = pdf_path_override
    else:
        report_txt = manifest.get("report_file", "")
        if report_txt:
            pdf_path = run_dir / (Path(report_txt).stem + ".pdf")
        else:
            def slug(s): return s.lower().replace(" ", "-")
            pdf_path = run_dir / f"lss-network-tools-report-{slug(client)}-{slug(location)}.pdf"

    pdf.output(str(pdf_path))
    print(str(pdf_path))


if __name__ == "__main__":
    try:
        main()
    except SystemExit:
        raise
    except Exception as exc:  # report a one-line reason, never a traceback
        print(f"{type(exc).__name__}: {exc}", file=sys.stderr)
        sys.exit(1)
